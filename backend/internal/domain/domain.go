// Package domain contains the core entities and business errors of the chat.
// It has no dependencies on transport or storage.
package domain

import (
	"time"

	"github.com/google/uuid"
)

type User struct {
	ID         uuid.UUID
	Username   string
	CreatedAt  time.Time
	LastSeenAt *time.Time
}

// Dialog is a private conversation between exactly two users.
// Invariant: UserA < UserB (enforced by the database), so a pair of users
// always maps to a single dialog regardless of who started it.
type Dialog struct {
	ID        uuid.UUID
	UserA     uuid.UUID
	UserB     uuid.UUID
	CreatedAt time.Time
}

func (d Dialog) HasMember(id uuid.UUID) bool { return d.UserA == id || d.UserB == id }

// Peer returns the other participant. The caller must ensure id is a member.
func (d Dialog) Peer(id uuid.UUID) uuid.UUID {
	if d.UserA == id {
		return d.UserB
	}
	return d.UserA
}

func (d Dialog) Members() []uuid.UUID { return []uuid.UUID{d.UserA, d.UserB} }

// DialogSummary is a dialog as seen by one of its participants.
type DialogSummary struct {
	Dialog
	Peer           User
	PeerOnline     bool
	LastMessage    *Message
	UnreadCount    int
	MyLastReadID   int64
	PeerLastReadID int64
}

type Message struct {
	ID       int64 // monotonically increasing, used for ordering and cursors
	DialogID uuid.UUID
	SenderID uuid.UUID
	// ClientID is generated by the sender and makes sending idempotent:
	// a retried send after a dropped connection never creates a duplicate.
	ClientID  uuid.UUID
	Body      string
	CreatedAt time.Time // assigned by the server, never trusted from the client
}

// NewMessage is the input for persisting a message.
type NewMessage struct {
	DialogID uuid.UUID
	SenderID uuid.UUID
	ClientID uuid.UUID
	Body     string
}
